package iq.tubedub.app

import org.json.JSONObject
import java.net.HttpURLConnection
import java.net.URL

object YouTubeCaptionClient {
    data class Result(val srt: String, val language: String, val autoGenerated: Boolean)

    fun extract(videoUrl: String): Result {
        val id = extractVideoId(videoUrl) ?: throw IllegalArgumentException("رابط YouTube مو واضح أو غير صالح")
        val watch = URL("https://www.youtube.com/watch?v=$id&hl=en")
        val html = requestText(watch, "text/html,application/xhtml+xml")
        val marker = "ytInitialPlayerResponse"
        val markerAt = html.indexOf(marker)
        if (markerAt < 0) throw IllegalStateException("YouTube ما رجّع بيانات الفيديو. جرّب من جديد أو استورد ملف ترجمة")
        val objectStart = html.indexOf('{', markerAt + marker.length)
        if (objectStart < 0) throw IllegalStateException("تعذر قراءة بيانات الفيديو من YouTube")
        val jsonText = extractJsonObject(html, objectStart)
        val root = JSONObject(jsonText)
        val captions = root.optJSONObject("captions")
            ?.optJSONObject("playerCaptionsTracklistRenderer")
            ?: throw IllegalStateException("هذا الفيديو ما بيه مسارات ترجمة ظاهرة")
        val tracks = captions.optJSONArray("captionTracks")
            ?: throw IllegalStateException("ما لكيت مسارات ترجمة لهذا الفيديو")
        if (tracks.length() == 0) throw IllegalStateException("ماكو ترجمة متاحة لهذا الفيديو")

        val available = (0 until tracks.length()).mapNotNull { index -> tracks.optJSONObject(index) }
        val selected = available.firstOrNull {
            it.optString("languageCode").startsWith("ar", true)
        } ?: available.first()
        val baseUrl = selected.optString("baseUrl")
        if (baseUrl.isBlank()) throw IllegalStateException("مسار الترجمة موجود لكن رابط تحميله ناقص")
        val captionUrl = if (baseUrl.contains("?")) "$baseUrl&fmt=json3" else "$baseUrl?fmt=json3"
        val captionJson = JSONObject(requestText(URL(captionUrl), "application/json,text/plain,*/*"))
        val events = captionJson.optJSONArray("events")
            ?: throw IllegalStateException("صيغة الترجمة اللي رجعت من YouTube مو مفهومة")
        val out = StringBuilder()
        var number = 1
        for (i in 0 until events.length()) {
            val event = events.optJSONObject(i) ?: continue
            val start = event.optLong("tStartMs", -1L)
            val duration = event.optLong("dDurationMs", 1800L)
            val segs = event.optJSONArray("segs") ?: continue
            val text = buildString {
                for (j in 0 until segs.length()) append(segs.optJSONObject(j)?.optString("utf8", "") ?: "")
            }.replace("\n", " ").trim()
            if (text.isBlank() || start < 0) continue
            val safeDuration = duration.coerceAtLeast(500L)
            out.append(number++).append('\n')
                .append(timestamp(start)).append(" --> ").append(timestamp(start + safeDuration)).append('\n')
                .append(text).append("\n\n")
        }
        if (out.isEmpty()) throw IllegalStateException("وصلت بيانات الفيديو بس ما بيها نص ترجمة")
        val lang = selected.optString("languageCode", "unknown")
        return Result(out.toString().trim(), lang, selected.optString("kind") == "asr")
    }

    private fun extractVideoId(value: String): String? {
        val patterns = listOf(
            Regex("youtu\\.be/([A-Za-z0-9_-]{11})"),
            Regex("[?&]v=([A-Za-z0-9_-]{11})"),
            Regex("youtube\\.com/(?:embed|shorts|live)/([A-Za-z0-9_-]{11})")
        )
        return patterns.firstNotNullOfOrNull { it.find(value)?.groupValues?.getOrNull(1) }
    }

    private fun requestText(url: URL, accept: String): String {
        val connection = (url.openConnection() as HttpURLConnection).apply {
            requestMethod = "GET"
            connectTimeout = 20_000
            readTimeout = 45_000
            setRequestProperty("User-Agent", "Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 Chrome/126.0 Mobile Safari/537.36")
            setRequestProperty("Accept", accept)
            setRequestProperty("Accept-Language", "en-US,en;q=0.9,ar;q=0.8")
            instanceFollowRedirects = true
        }
        try {
            val code = connection.responseCode
            val stream = if (code in 200..299) connection.inputStream else connection.errorStream
            val body = stream?.bufferedReader(Charsets.UTF_8)?.use { it.readText() }.orEmpty()
            if (code !in 200..299) throw IllegalStateException("YouTube ردّ برمز HTTP $code. ممكن يمنع الطلب أو يحتاج تحقق")
            return body
        } finally {
            connection.disconnect()
        }
    }

    private fun extractJsonObject(text: String, start: Int): String {
        var depth = 0
        var inString = false
        var escaped = false
        for (i in start until text.length) {
            val c = text[i]
            if (inString) {
                if (escaped) escaped = false
                else if (c == '\\') escaped = true
                else if (c == '"') inString = false
            } else {
                when (c) {
                    '"' -> inString = true
                    '{' -> depth++
                    '}' -> {
                        depth--
                        if (depth == 0) return text.substring(start, i + 1)
                    }
                }
            }
        }
        throw IllegalStateException("بيانات YouTube ناقصة أو انقطعت")
    }

    private fun timestamp(ms: Long): String {
        val total = ms.coerceAtLeast(0L)
        val hours = total / 3_600_000
        val minutes = (total % 3_600_000) / 60_000
        val seconds = (total % 60_000) / 1_000
        val millis = total % 1_000
        return "%02d:%02d:%02d,%03d".format(hours, minutes, seconds, millis)
    }
}
