package iq.tubedub.app

import android.graphics.Color as AndroidColor
import android.media.MediaPlayer
import android.net.Uri
import android.os.Bundle
import android.speech.tts.TextToSpeech
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import java.io.File
import java.util.Locale
import kotlin.concurrent.thread

class MainActivity : ComponentActivity(), TextToSpeech.OnInitListener {
    private var videoUrl by mutableStateOf("")
    private var sourceSubtitle by mutableStateOf("")
    private var iraqiSubtitle by mutableStateOf("")
    private var geminiKey by mutableStateOf("")
    private var fishKey by mutableStateOf("")
    private var voiceId by mutableStateOf("")
    private var statusMessage by mutableStateOf("جاهز. الصق رابط فيديو أو استورد ملف ترجمة حتى نبدأ.")
    private var isWorking by mutableStateOf(false)
    private var isPlayingAudio by mutableStateOf(false)

    private lateinit var securePrefs: SecurePrefs
    private var tts: TextToSpeech? = null
    private var ttsReady = false
    private var player: MediaPlayer? = null

    private val importSubtitleLauncher = registerForActivityResult(
        ActivityResultContracts.OpenDocument()
    ) { uri ->
        uri?.let(::readSubtitle)
    }

    private val exportSubtitleLauncher = registerForActivityResult(
        ActivityResultContracts.CreateDocument("application/x-subrip")
    ) { uri ->
        uri?.let(::writeSubtitle)
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        window.statusBarColor = AndroidColor.rgb(10, 10, 20)
        window.navigationBarColor = AndroidColor.rgb(10, 10, 20)
        window.decorView.systemUiVisibility = 0

        securePrefs = SecurePrefs(this)
        loadSettings()
        tts = TextToSpeech(this, this)

        setContent {
            TubeDubTheme {
                TubeDubApp(
                    videoUrl = videoUrl,
                    onVideoUrlChange = { videoUrl = it },
                    sourceSubtitle = sourceSubtitle,
                    onSourceSubtitleChange = { sourceSubtitle = it },
                    iraqiSubtitle = iraqiSubtitle,
                    onIraqiSubtitleChange = { iraqiSubtitle = it },
                    geminiKey = geminiKey,
                    onGeminiKeyChange = { geminiKey = it },
                    fishKey = fishKey,
                    onFishKeyChange = { fishKey = it },
                    voiceId = voiceId,
                    onVoiceIdChange = { voiceId = it },
                    statusMessage = statusMessage,
                    isWorking = isWorking,
                    isPlayingAudio = isPlayingAudio,
                    onExtractYoutube = ::extractYoutube,
                    onImportSubtitle = {
                        importSubtitleLauncher.launch(
                            arrayOf("application/x-subrip", "text/vtt", "text/plain", "application/octet-stream", "*/*")
                        )
                    },
                    onTranslate = ::translate,
                    onExportSubtitle = {
                        if (iraqiSubtitle.isBlank()) showStatus("ماكو ترجمة عراقية حتى نصدرها")
                        else exportSubtitleLauncher.launch("tubedub-iraqi.srt")
                    },
                    onFishDub = ::generateFishAudio,
                    onLocalSpeak = ::speakLocal,
                    onStopAudio = ::stopAudio,
                    onSaveSettings = ::saveSettings
                )
            }
        }
    }

    private fun extractYoutube() {
        val link = videoUrl.trim()
        if (link.isBlank()) return showStatus("الصق رابط الفيديو أولاً")
        work("دا أستخرج الترجمة من YouTube...") {
            val result = YouTubeCaptionClient.extract(link)
            runOnUiThread {
                sourceSubtitle = result.srt
                showStatus(
                    "تم استخراج الترجمة. اللغة: ${result.language}" +
                        if (result.autoGenerated) " — تلقائية" else " — يدوية"
                )
            }
        }
    }

    private fun readSubtitle(uri: Uri) {
        work("دا أقرأ ملف الترجمة...") {
            val raw = contentResolver.openInputStream(uri)
                ?.bufferedReader(Charsets.UTF_8)
                ?.use { it.readText() }
                ?: throw IllegalStateException("ما گدرت أفتح الملف")
            val normalized = SubtitleParser.normalize(raw)
            runOnUiThread {
                sourceSubtitle = normalized
                showStatus("تم استيراد الملف. راجع النص قبل الترجمة.")
            }
        }
    }

    private fun writeSubtitle(uri: Uri) {
        work("دا أحفظ ملف الترجمة...") {
            val output = SubtitleParser.outputForExport(iraqiSubtitle)
            contentResolver.openOutputStream(uri)
                ?.bufferedWriter(Charsets.UTF_8)
                ?.use { it.write(output) }
                ?: throw IllegalStateException("ما گدرت أكتب الملف")
            runOnUiThread { showStatus("تم تصدير ملف SRT بنجاح.") }
        }
    }

    private fun translate() {
        val source = sourceSubtitle.trim()
        val key = geminiKey.trim()
        if (source.isBlank()) return showStatus("استخرج الترجمة أو استورد ملف أولاً")
        if (key.isBlank()) return showStatus("أدخل مفتاح Google AI Studio من الإعدادات")
        work("Gemini دا يحوّل النص للعراقي. النص الطويل ينقسم إلى أجزاء...") {
            val translated = GeminiTranslator.translateToIraqi(source, key)
            runOnUiThread {
                iraqiSubtitle = translated
                showStatus("اكتملت الترجمة العراقية. راجع الأسماء والتوقيتات قبل التصدير.")
            }
        }
    }

    private fun generateFishAudio() {
        val text = iraqiSubtitle.trim()
        val key = fishKey.trim()
        val voice = voiceId.trim()
        if (text.isBlank()) return showStatus("اكتب أو ترجم النص العراقي أولاً")
        if (key.isBlank()) return showStatus("أدخل مفتاح Fish Audio من الإعدادات")
        if (text.length > 3500) {
            return showStatus("النص أطول من حد النسخة الحالية للدبلجة. قسّمه إلى مقاطع أقصر حالياً.")
        }
        work("Fish Audio دا يولّد الصوت...") {
            val file = File(cacheDir, "tubedub-voice-${System.currentTimeMillis()}.mp3")
            FishAudioClient.synthesize(text, key, voice, file)
            runOnUiThread {
                showStatus("اكتمل توليد الصوت. دا أشغّله...")
                playAudio(file)
            }
        }
    }

    private fun playAudio(file: File) {
        try {
            player?.release()
            isPlayingAudio = false
            player = MediaPlayer().apply {
                setDataSource(file.absolutePath)
                setOnPreparedListener {
                    it.start()
                    isPlayingAudio = true
                    showStatus("الصوت دا يشتغل")
                }
                setOnCompletionListener {
                    it.release()
                    if (player === it) player = null
                    isPlayingAudio = false
                    showStatus("انتهى تشغيل الصوت")
                }
                setOnErrorListener { mp, _, _ ->
                    mp.release()
                    player = null
                    isPlayingAudio = false
                    showStatus("صار خطأ بتشغيل ملف الصوت")
                    true
                }
                prepareAsync()
            }
        } catch (e: Exception) {
            isPlayingAudio = false
            showStatus("ما گدرت أشغّل الصوت: ${e.message}")
        }
    }

    private fun stopAudio() {
        try {
            player?.let { current ->
                if (current.isPlaying) current.stop()
                current.release()
            }
        } catch (_: Exception) {
            // The player may already have completed or failed.
        } finally {
            player = null
            isPlayingAudio = false
            showStatus("تم إيقاف تشغيل الصوت")
        }
    }

    private fun speakLocal() {
        val text = iraqiSubtitle.trim()
        if (text.isBlank()) return showStatus("اكتب النص العراقي أولاً")
        if (!ttsReady) return showStatus("محرك النطق بالجهاز بعده ما جاهز")
        tts?.language = Locale("ar", "IQ")
        tts?.speak(text.take(3500), TextToSpeech.QUEUE_FLUSH, null, "tubedub-local-tts")
        showStatus("طلبت النطق المحلي. جودة اللهجة تعتمد على الأصوات المثبتة بجهازك.")
    }

    private fun saveSettings() {
        try {
            securePrefs.put("gemini", geminiKey.trim())
            securePrefs.put("fish", fishKey.trim())
            securePrefs.put("voice", voiceId.trim())
            showStatus("تم حفظ المفاتيح بمخزن Android Keystore")
        } catch (e: Exception) {
            showStatus("تعذر حفظ الإعدادات: ${e.message}")
        }
    }

    private fun loadSettings() {
        geminiKey = securePrefs.get("gemini")
        fishKey = securePrefs.get("fish")
        voiceId = securePrefs.get("voice")
    }

    private fun work(message: String, operation: () -> Unit) {
        if (isWorking) return
        isWorking = true
        showStatus(message)
        thread(name = "tubedub-worker") {
            try {
                operation()
            } catch (e: Exception) {
                runOnUiThread { showStatus(e.message ?: "صار خطأ غير معروف") }
            } finally {
                runOnUiThread { isWorking = false }
            }
        }
    }

    private fun showStatus(message: String) {
        statusMessage = message
    }

    override fun onInit(statusCode: Int) {
        ttsReady = statusCode == TextToSpeech.SUCCESS
        if (ttsReady) tts?.language = Locale("ar", "IQ")
    }

    override fun onDestroy() {
        player?.release()
        player = null
        tts?.stop()
        tts?.shutdown()
        super.onDestroy()
    }
}
